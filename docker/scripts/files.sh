generate_cli_scaffold() {
    {
        printf '<?php\n\ndeclare(strict_types=1);\n\n'
        cat <<'EOL'
if (PHP_SAPI !== 'cli') {
    exit('This script must be run from the terminal.' . PHP_EOL);
}

EOL
        welcome_php_common
        cat <<'EOL'

$nextSteps = [
    'Create your commands in the commands/ directory.',
    'Run them with: make php c=commands/<file>.php',
    ...$commonSteps,
];

$useColors = stream_isatty(STDOUT) && getenv('NO_COLOR') === false;
$color = static fn (string $text, string $code): string => $useColors ? "\033[{$code}m{$text}\033[0m" : $text;
$title = static fn (string $text): string => PHP_EOL . $color($text, '1;36') . PHP_EOL;

echo PHP_EOL . $color(sprintf('Welcome to %s!', $project['name']), '1;35') . PHP_EOL;
echo sprintf('Your cli project is running on PHP %s (timezone %s).', PHP_VERSION, $project['timezone']) . PHP_EOL;

echo $title('Next steps');
foreach ($nextSteps as $index => $step) {
    printf('  %d. %s%s', $index + 1, $step, PHP_EOL);
}

echo $title('Services');
$failures = 0;
foreach ($services as $service) {
    $status = $service['error'] === null ? $color('✓', '32') : $color('✗', '31');
    $failures += $service['error'] === null ? 0 : 1;

    printf('  %s %s %s%s', $status, $color(str_pad($service['name'], 16), '1'), $service['internal'], PHP_EOL);
    if ($service['external'] !== '') {
        printf('    %s from your machine: %s%s', str_repeat(' ', 16), $service['external'], PHP_EOL);
    }
    printf('    %s %s%s', str_repeat(' ', 16), $service['details'], PHP_EOL);
    if ($service['error'] !== null) {
        printf('    %s %s%s', str_repeat(' ', 16), $color($service['error'], '31'), PHP_EOL);
    }
}

echo $title('Useful commands');
foreach ($commands as $command => $description) {
    printf('  %s %s%s', $color(str_pad($command, 42), '33'), $description, PHP_EOL);
}

if ($packages !== []) {
    echo $title('Suggested packages');
    foreach ($packages as $package => $description) {
        printf('  %s %s%s', $color(str_pad('make composer c="require ' . $package . '"', 56), '33'), $description, PHP_EOL);
    }
}

echo PHP_EOL;

exit($failures === 0 ? 0 : 1);
EOL
    } | write_if_missing "$ROOT_DIR/commands/welcome.php"
}

# Versão do PHPUnit compatível com cada versão do PHP
phpunit_constraint() {
    case "$PHP_VERSION" in
        8.2) printf '^11.5' ;;
        8.3) printf '^12.5' ;;
        *)   printf '^13.4' ;;
    esac
}

generate_composer_scaffold() {
    local package_name="${PROJECT_NAME_SNAKE_CASE//_/-}"
    local phpunit_version
    phpunit_version="$(phpunit_constraint)"

    write_if_missing "$ROOT_DIR/composer.json" <<EOL
{
    "name": "app/${package_name}",
    "description": "${PROJECT_NAME}",
    "type": "project",
    "license": "proprietary",
    "require": {
        "php": "^${PHP_VERSION}"
    },
    "require-dev": {
        "friendsofphp/php-cs-fixer": "^3.95",
        "phpstan/phpstan": "^2.3",
        "phpunit/phpunit": "${phpunit_version}"
    },
    "autoload": {
        "psr-4": {
            "${PROJECT_NAMESPACE}\\\\": "src/"
        }
    },
    "autoload-dev": {
        "psr-4": {
            "${PROJECT_NAMESPACE}\\\\Tests\\\\": "tests/"
        }
    },
    "scripts": {
        "test": "phpunit",
        "stan": "phpstan analyse --memory-limit=512M",
        "cs": "php-cs-fixer fix --dry-run --diff",
        "cs:fix": "php-cs-fixer fix"
    },
    "config": {
        "sort-packages": true,
        "optimize-autoloader": true
    }
}
EOL

    write_if_missing "$ROOT_DIR/src/Greeting.php" <<EOL
<?php

declare(strict_types=1);

namespace ${PROJECT_NAMESPACE};

final readonly class Greeting
{
    public function __construct(private string \$name) {}

    public function message(): string
    {
        return sprintf('Hello, %s!', \$this->name);
    }
}
EOL

    write_if_missing "$ROOT_DIR/tests/GreetingTest.php" <<EOL
<?php

declare(strict_types=1);

namespace ${PROJECT_NAMESPACE}\\Tests;

use ${PROJECT_NAMESPACE}\\Greeting;
use PHPUnit\\Framework\\TestCase;

final class GreetingTest extends TestCase
{
    public function testMessageContainsTheName(): void
    {
        self::assertSame('Hello, World!', (new Greeting('World'))->message());
    }
}
EOL

    write_if_missing "$ROOT_DIR/phpunit.xml.dist" <<'EOL'
<?xml version="1.0" encoding="UTF-8"?>
<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"
         bootstrap="vendor/autoload.php"
         cacheDirectory=".phpunit.cache"
         colors="true"
         failOnRisky="true"
         failOnWarning="true">
    <testsuites>
        <testsuite name="default">
            <directory>tests</directory>
        </testsuite>
    </testsuites>
    <source>
        <include>
            <directory>src</directory>
        </include>
    </source>
</phpunit>
EOL

    write_if_missing "$ROOT_DIR/phpstan.neon.dist" <<'EOL'
parameters:
    level: 8
    paths:
        - src
        - tests
EOL

    write_if_missing "$ROOT_DIR/.php-cs-fixer.dist.php" <<'EOL'
<?php

declare(strict_types=1);

$finder = (new PhpCsFixer\Finder())
    ->in([__DIR__ . '/src', __DIR__ . '/tests']);

return (new PhpCsFixer\Config())
    ->setRiskyAllowed(true)
    ->setRules([
        '@PER-CS' => true,
        'declare_strict_types' => true,
        'no_unused_imports' => true,
        'ordered_imports' => true,
        'strict_param' => true,
    ])
    ->setFinder($finder);
EOL

    print_info "Run 'make install' after 'make start' to install the Composer dependencies"
}
