#!/usr/bin/env bash
# shellcheck disable=SC2034 # Variáveis lidas indiretamente (write_env_var)

# Escreve NOME='valor' no .env apenas se o valor não estiver vazio.
# Os valores já foram validados (sem aspas simples/quebras de linha).
write_env_var() {
    local name="$1"
    local value="${!name:-}"

    if [[ -n "$value" ]]; then
        printf "%s='%s'\n" "$name" "$value"
    fi
}

generate_env_file() {
    local var
    local vars=(
        PROJECT_NAME
        PROJECT_NAME_SNAKE_CASE
        COMPOSE_PROJECT_NAME
        APP_TYPE
        PHP_VERSION
        PHP_EXTENSIONS
        TZ
        HOST_UID
        HOST_GID
        BIND_ADDRESS
        PROJECT_PORT
        DATABASE
        DB_PORT
        DB_NAME
        DB_USER
        DB_PASSWORD
        DB_ROOT_PASSWORD
        MAILPIT_SMTP_PORT
        MAILPIT_WEB_PORT
        RABBITMQ_PORT
        RABBITMQ_WEB_PORT
        RABBITMQ_USER
        RABBITMQ_PASSWORD
        REDIS_PORT
        MEMCACHED_PORT
        MEILISEARCH_PORT
        MEILISEARCH_KEY
        OPENSEARCH_PORT
        ELASTICSEARCH_PORT
        RUSTFS_PORT
        RUSTFS_CONSOLE_PORT
        RUSTFS_ACCESS_KEY
        RUSTFS_SECRET_KEY
        KAFKA_PORT
        MERCURE_PORT
        MERCURE_JWT_SECRET
        SELENIUM_PORT
        SELENIUM_VNC_PORT
        WORKER_COMMAND
    )

    COMPOSE_PROJECT_NAME="$PROJECT_NAME_SNAKE_CASE"
    HOST_UID="$(id -u)"
    HOST_GID="$(id -g)"
    # Portas publicadas apenas na máquina local. Use 0.0.0.0 para expor na rede.
    BIND_ADDRESS="127.0.0.1"
    local TZ="$TZ_VALUE"

    # Cria o arquivo já com permissão restrita, pois contém senhas
    (
        umask 077
        {
            printf '# Generated by docker/setup.sh on %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"
            for var in "${vars[@]}"; do
                write_env_var "$var"
            done
        } > "$ENV_FILE"
    )
    chmod 600 "$ENV_FILE"

    print_info ".env file generated in: $ENV_FILE"
}

# Cria diretórios de configuração versionáveis do serviço (ex.: config/initdb.d)
# com o usuário atual, evitando que o Docker os crie como root.
create_config_dirs() {
    local service="$1"
    shift
    local dir

    for dir in "$@"; do
        mkdir -p "$SERVICES_ROOT_DIR/$service/config/$dir"
    done
}

# O Compose não permite "extends" entre arquivos mesclados. Para que worker e scheduler
# recebam as mesmas variáveis que os templates injetam no serviço php (DB_HOST, REDIS_HOST...),
# copia as linhas de "php: environment:" de cada template para um override temporário.
# php_env_override <arquivo de saída> <serviço destino>... ; templates em SERVICES_FILES
php_env_override() {
    local output="$1"
    shift
    local target file

    {
        printf 'services:\n'
        for target in "$@"; do
            printf '  %s:\n    environment:\n' "$target"
            for file in "${SERVICES_FILES[@]}"; do
                [[ "$file" == */php/php.yml ]] && continue
                awk '
                    /^[^ ]/ || /^  [^ ]/ { in_php = ($0 == "  php:"); in_env = 0; next }
                    in_php && /^    environment:/ { in_env = 1; next }
                    in_php && /^    [^ ]/ { in_env = 0 }
                    in_php && in_env && /^      [^ ]/ { print }
                ' "$file"
            done
        done
    } > "$output"
}

# Escreve o conteúdo de stdin em um arquivo somente se ele ainda não existir
write_if_missing() {
    local file="$1"

    if [[ -e "$file" ]]; then
        print_warning "Skipped (already exists): ${file#"$ROOT_DIR"/}"
        cat > /dev/null
        return 0
    fi

    mkdir -p "$(dirname "$file")"
    cat > "$file"
    print_success "Created: ${file#"$ROOT_DIR"/}"
}

# Cria o ponto de entrada conforme o tipo de projeto:
#   web -> public/index.php (página HTML de boas-vindas)
#   api -> public/index.php (JSON de boas-vindas)
#   cli -> commands/welcome.php (boas-vindas no terminal)
generate_app_entrypoint() {
    case "$APP_TYPE" in
        web) generate_web_scaffold ;;
        api) generate_api_scaffold ;;
        cli) generate_cli_scaffold ;;
    esac

    if has_service worker; then
        generate_worker_scaffold
    fi

    if has_service scheduler; then
        generate_scheduler_scaffold
    fi
}

