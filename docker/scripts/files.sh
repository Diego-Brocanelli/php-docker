# Bloco PHP comum às boas-vindas. Lê tudo das variáveis de ambiente do container
# em tempo de execução (nada fica desatualizado se o .env mudar) e testa a conexão
# com cada serviço.
welcome_php_common() {
    cat <<'EOL'
$env = static fn (string $name, string $default = ''): string => (string) (getenv($name) ?: $default);

$project = [
    'name' => $env('APP_NAME', 'PHP Docker'),
    'type' => $env('APP_TYPE', 'web'),
    'url' => $env('APP_URL'),
    'timezone' => date_default_timezone_get(),
